import { createRequire } from "node:module";
import { mkdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const require = createRequire(path.resolve("tmp-perf/package.json"));
const sharp = require("sharp");

const publicDir = path.resolve("apps/site/public");
const outDir = path.join(publicDir, "images/opt");

const jobs = [
  ["images/home-2/isometric-city.png", [480, 768, 1024, 1400], "illustration"],
  ["images/home-2/checkout-suite.png", [480, 800, 1200], "illustration"],
  ["images/home-2/phones/new-sale.png", [320, 480, 720], "ui"],
  ["images/home-2/phones/inventory.png", [320, 480, 720], "ui"],
  ["images/home-2/phones/analytics.png", [320, 480, 720], "ui"],
  ["images/home-2/cafe.png", [480, 800, 1200], "illustration"],
  ["images/home-2/restaurant.png", [480, 800, 1200], "illustration"],
  ["images/home-2/supermarket.png", [480, 800, 1200], "illustration"],
  ["images/home-2/electronics.png", [480, 800, 1200], "illustration"],
  ["images/home-2/fashion.png", [480, 800, 1200], "illustration"],
  ["images/home-2/wholesale.png", [480, 800, 1200], "illustration"],
  ["images/home-2/orange-ribbons.png", [800, 1400], "illustration"],
  ["pos/terminal.png", [480, 819], "ui"],
  ["portal/macbook.png", [480, 800, 1200], "ui"],
  ["portal/dashboard.jpg", [640, 960, 1280], "photo"],
  ["pos/register.jpg", [640, 960, 1280], "photo"],
  ["images/home-3/quick-service.jpg", [480, 800, 1200], "photo"],
];

const quality = {
  illustration: { webp: 84, avif: 56 },
  ui: { webp: 88, avif: 64 },
  photo: { webp: 80, avif: 52 },
};

await mkdir(outDir, { recursive: true });
const manifest = {};
let originalBytes = 0;
let derivativeBytes = 0;

for (const [src, requested, kind] of jobs) {
  const input = path.join(publicDir, src);
  const before = (await stat(input)).size;
  originalBytes += before;
  const image = sharp(input);
  const meta = await image.metadata();
  const widths = [...new Set(requested.filter((width) => width < meta.width).concat(meta.width))].sort((a, b) => a - b);
  const stem = src.replace(/\.[^.]+$/, "").replaceAll("/", "-");
  const avif = [];
  const webp = [];
  for (const width of widths) {
    const resized = sharp(input).resize({ width, withoutEnlargement: true });
    const avifName = `${stem}-${width}.avif`;
    const webpName = `${stem}-${width}.webp`;
    const avifBuf = await resized.clone().avif({ quality: quality[kind].avif, effort: 4 }).toBuffer();
    const webpBuf = await resized.clone().webp({ quality: quality[kind].webp, effort: 4 }).toBuffer();
    await writeFile(path.join(outDir, avifName), avifBuf);
    await writeFile(path.join(outDir, webpName), webpBuf);
    derivativeBytes += avifBuf.length + webpBuf.length;
    avif.push(`/images/opt/${avifName} ${width}w`);
    webp.push(`/images/opt/${webpName} ${width}w`);
  }
  manifest[src.startsWith("/") ? src : `/${src}`] = {
    width: meta.width,
    height: meta.height,
    avif: avif.join(", "),
    webp: webp.join(", "),
    bytes: before,
  };
  console.log(`${src} ${meta.width}x${meta.height} ${before} -> widths ${widths.join(",")}`);
}

const lines = [
  "/* Generated by scripts/optimize-site-images.mjs. Displayed images only. */",
  "export const IMAGE_SETS = {",
];
for (const [src, item] of Object.entries(manifest)) {
  lines.push(`  ${JSON.stringify(src)}: { width: ${item.width}, height: ${item.height}, avif: ${JSON.stringify(item.avif)}, webp: ${JSON.stringify(item.webp)} },`);
}
lines.push("} as const;", "");
await writeFile(path.resolve("apps/site/src/image-sets.ts"), lines.join("\n"));
console.log(`original ${originalBytes} derivative files ${derivativeBytes}`);
