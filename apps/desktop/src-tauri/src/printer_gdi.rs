//! Windows-driver receipt printing.
//!
//! A native Windows driver, such as Toshiba Native Windows Driver on a `Toshiba:` port, renders a
//! GDI page. Raw ESC/POS sent as datatype RAW is accepted by the spooler and then discarded, so the
//! printer feeds and cuts a blank slip. This module draws the same 1-bit raster the receipt
//! renderer already produced. It does not send a drawer pulse.

use crate::printer_discovery::{self, RENDER_FAILED, TRANSMIT_FAILED};

/// Packed 1-bit rows are 203 dots per inch. 384 dots is 58 mm paper and 576 dots is 80 mm paper.
pub fn paper_size_tenths(width_dots: u32, height_dots: u32) -> (i16, i16) {
    let width = if width_dots <= 384 { 580 } else { 800 };
    // Tenths of a millimetre at 203 dpi, plus a short tail so the last line is not clipped.
    // The previous 300 mm cap kept only the top of a long slip.
    let length = ((height_dots as i64) * 254 / 203 + 150).clamp(400, 32_000);
    (width, length as i16)
}

/// Source raster dots are generated by the web receipt renderer at 203 DPI.
/// Convert them to the destination driver's physical pixel dimensions without changing
/// the receipt's intended paper width. A driver that cannot fit the image is rejected
/// by `print_gdi` instead of silently clipping or shrinking it.
#[cfg_attr(not(test), allow(dead_code))]
pub fn gdi_destination(src_w: u32, src_h: u32, dpi: i32, _printable: i32) -> (i32, i32) {
    let dpi = if dpi <= 0 { 203 } else { dpi };
    let scale = |dots: u32| -> i32 {
        ((u64::from(dots) * dpi as u64 + 101) / 203)
            .clamp(1, i32::MAX as u64) as i32
    };
    (scale(src_w), scale(src_h))
}

/// One continuous custom roll page for the complete receipt.
#[cfg_attr(not(test), allow(dead_code))]
pub fn roll_page(height: u32) -> Vec<(u32, u32)> {
    vec![(0, height.max(1))]
}

const MAX_RECEIPT_WIDTH_DOTS: u32 = 2_048;
const MAX_RECEIPT_HEIGHT_DOTS: u32 = 20_000;
const MAX_DIB_BYTES: usize = 96 * 1024 * 1024;

fn raster_layout(width: u32, height: u32, packed_len: usize) -> Result<(usize, usize), String> {
    if width == 0
        || height == 0
        || width > MAX_RECEIPT_WIDTH_DOTS
        || height > MAX_RECEIPT_HEIGHT_DOTS
    {
        return Err("Receipt dimensions are invalid or exceed the safe limit.".into());
    }

    let row_bytes = (width as usize)
        .checked_add(7)
        .ok_or_else(|| "Receipt row size overflow.".to_string())?
        / 8;
    let expected = row_bytes
        .checked_mul(height as usize)
        .ok_or_else(|| "Receipt raster size overflow.".to_string())?;
    if packed_len != expected {
        return Err("The receipt image is malformed.".into());
    }

    let stride = (width as usize)
        .checked_mul(3)
        .and_then(|bytes| bytes.checked_add(3))
        .map(|bytes| bytes / 4 * 4)
        .ok_or_else(|| "Receipt bitmap stride overflow.".to_string())?;
    let dib_bytes = stride
        .checked_mul(height as usize)
        .ok_or_else(|| "Receipt bitmap size overflow.".to_string())?;
    if dib_bytes > MAX_DIB_BYTES {
        return Err("Receipt bitmap exceeds the safe memory limit.".into());
    }
    Ok((row_bytes, stride))
}

/// Check only visible pixels. Unused low bits at the right edge of a packed row are padding,
/// not evidence that the receipt contains printable ink.
pub fn has_visible_ink(width: u32, height: u32, packed: &[u8]) -> Result<bool, String> {
    let (row_bytes, _) = raster_layout(width, height, packed.len())?;
    for y in 0..height as usize {
        let row = &packed[y * row_bytes..(y + 1) * row_bytes];
        for x in 0..width as usize {
            if row[x >> 3] & (0x80u8 >> (x & 7)) != 0 {
                return Ok(true);
            }
        }
    }
    Ok(false)
}

/// Expands MSB-first 1-bit rows (1 = black) into a top-down 24-bit BGR DIB.
#[cfg_attr(not(test), allow(dead_code))]
pub fn expand_bgr24(width: u32, height: u32, packed: &[u8]) -> Result<(usize, Vec<u8>), String> {
    if !has_visible_ink(width, height, packed)? {
        return Err(RENDER_FAILED.into());
    }
    expand_rows(width, height, packed)
}

#[cfg_attr(not(test), allow(dead_code))]
fn expand_rows(width: u32, height: u32, packed: &[u8]) -> Result<(usize, Vec<u8>), String> {
    let (row_bytes, stride) = raster_layout(width, height, packed.len())?;
    let dib_len = stride
        .checked_mul(height as usize)
        .ok_or_else(|| "Receipt bitmap size overflow.".to_string())?;
    let mut pixels = vec![255u8; dib_len];

    for y in 0..height as usize {
        let source_row = &packed[y * row_bytes..(y + 1) * row_bytes];
        for x in 0..width as usize {
            if source_row[x >> 3] & (0x80u8 >> (x & 7)) != 0 {
                let offset = y * stride + x * 3;
                pixels[offset..offset + 3].fill(0);
            }
        }
    }
    Ok((stride, pixels))
}

/// Rows in one printer page. Splitting into bands prevents the Windows driver
/// from truncating very tall bitmaps.
pub const GDI_BAND_ROWS: u32 = 128;

/// Paper for one band, in tenths of a millimetre, with no extra tail. A tail is a white cut through the next line.
pub fn band_paper_tenths(width_dots: u32, height_dots: u32) -> (i16, i16) {
    let width = if width_dots <= 384 { 580 } else { 800 };
    let length = ((height_dots.max(1) as i64) * 254 / 203).clamp(1, 32_000);
    (width, length as i16)
}

pub fn gdi_bands(height: u32) -> Vec<(u32, u32)> {
    let height = height.max(1);
    let mut bands = Vec::new();
    let mut start = 0u32;
    while start < height {
        let rows = (height - start).min(GDI_BAND_ROWS);
        bands.push((start, rows));
        start += rows;
    }
    bands
}

/// Bands sized to the page height the driver ACTUALLY reports. Some native POS drivers
/// ignore `dmPaperLength` and feed their own default page; banding by `VERTRES` makes
/// every band exactly one page, so pages tile into one continuous slip with no gaps and
/// no bitmap ever taller than the page it is drawn on.
pub fn bands_for_page(height: u32, page_rows: u32) -> Vec<(u32, u32)> {
    let height = height.max(1);
    let page_rows = page_rows.max(1);
    let mut bands = Vec::new();
    let mut start = 0u32;
    while start < height {
        let rows = (height - start).min(page_rows);
        bands.push((start, rows));
        start += rows;
    }
    bands
}

/// Bottom-up 24-bit BGR for the rows `[start, start + rows)`. Black stays black.
/// The first bytes are the last source row, which is what `SetDIBitsToDevice` expects.
pub fn band_bgr24(width: u32, packed: &[u8], start: u32, rows: u32) -> Result<Vec<u8>, String> {
    let row_bytes = width.div_ceil(8) as usize;
    let stride = (width as usize)
        .checked_mul(3)
        .and_then(|bytes| bytes.checked_add(3))
        .map(|bytes| bytes / 4 * 4)
        .ok_or_else(|| "Receipt bitmap stride overflow.".to_string())?;
    let from = start as usize * row_bytes;
    let to = from
        .checked_add(rows as usize * row_bytes)
        .ok_or_else(|| "Receipt bitmap size overflow.".to_string())?;
    if width == 0 || rows == 0 || to > packed.len() {
        return Err("The receipt image is malformed.".into());
    }
    let dib_len = stride
        .checked_mul(rows as usize)
        .ok_or_else(|| "Receipt bitmap size overflow.".to_string())?;
    let mut out = vec![255u8; dib_len];
    for y in 0..rows as usize {
        let source_row = &packed[from + y * row_bytes..from + (y + 1) * row_bytes];
        let dst_row = (rows as usize - 1 - y) * stride;
        for x in 0..width as usize {
            if source_row[x >> 3] & (0x80u8 >> (x & 7)) != 0 {
                let offset = dst_row + x * 3;
                out[offset..offset + 3].fill(0);
            }
        }
    }
    Ok(out)
}

/// Bottom-up 1-bit rows, DWORD aligned. Bit 1 stays black. Padding bits stay white.
pub fn band_1bit(width: u32, packed: &[u8], start: u32, rows: u32) -> Result<Vec<u8>, String> {
    let row_bytes = width.div_ceil(8) as usize;
    let stride = (width as usize).div_ceil(32) * 4;
    let from = start as usize * row_bytes;
    let to = from + rows as usize * row_bytes;
    if width == 0 || rows == 0 || to > packed.len() {
        return Err("The receipt image is malformed.".into());
    }
    let mut out = vec![0u8; stride * rows as usize];
    for y in 0..rows as usize {
        let src = from + y * row_bytes;
        let dst = (rows as usize - 1 - y) * stride;
        out[dst..dst + row_bytes].copy_from_slice(&packed[src..src + row_bytes]);
    }
    Ok(out)
}

/// True when graphic bytes appear before the feed and cut commands.
pub fn graphics_precede_cut(bytes: &[u8]) -> bool {
    let image = bytes.windows(4).position(|window| window == [0x1d, b'v', b'0', 0]);
    let cut = bytes.windows(3).position(|window| window == [0x1d, b'V', 66]);
    match (image, cut) {
        (Some(image), Some(cut)) => image < cut && bytes[image..cut].iter().any(|byte| *byte != 0),
        _ => false,
    }
}

#[cfg(windows)]
fn set_band_paper(bytes: &mut [u8], width: u32, height: u32) {
    use windows_sys::Win32::Graphics::Gdi::{
        DEVMODEW, DM_ORIENTATION, DM_PAPERLENGTH, DM_PAPERSIZE, DM_PAPERWIDTH, DM_PRINTQUALITY, DM_SCALE,
        DM_YRESOLUTION, DMPAPER_USER,
    };
    if bytes.len() < std::mem::size_of::<DEVMODEW>() {
        return;
    }
    unsafe {
        let mode = bytes.as_mut_ptr().cast::<DEVMODEW>();
        // height here MUST be the band height, never the full receipt height.
        let (paper_w, paper_h) = band_paper_tenths(width, height);
        (*mode).dmFields |=
            DM_ORIENTATION | DM_PAPERSIZE | DM_PAPERLENGTH | DM_PAPERWIDTH | DM_SCALE | DM_PRINTQUALITY | DM_YRESOLUTION;
        (*mode).Anonymous1.Anonymous1.dmOrientation = 1;
        (*mode).Anonymous1.Anonymous1.dmPaperSize = DMPAPER_USER as i16;
        (*mode).Anonymous1.Anonymous1.dmPaperLength = paper_h;
        (*mode).Anonymous1.Anonymous1.dmPaperWidth = paper_w;
        (*mode).Anonymous1.Anonymous1.dmScale = 100;
        (*mode).Anonymous1.Anonymous1.dmPrintQuality = 203;
        (*mode).dmYResolution = 203;
    }
}

#[cfg(windows)]
pub fn print_gdi(
    name: &str,
    width: u32,
    height: u32,
    packed: &[u8],
    copies: u32,
) -> Result<(), String> {
    use windows_sys::Win32::Foundation::GetLastError;
    use windows_sys::Win32::Graphics::Gdi::{
        CreateDCW, DeleteDC, GetDeviceCaps, SetMapMode, SetViewportOrgEx, SetWindowOrgEx, HORZRES, LOGPIXELSX,
        LOGPIXELSY, MM_TEXT, VERTRES,
    };
    use windows_sys::Win32::Graphics::Printing::{ClosePrinter, OpenPrinterW, PRINTER_HANDLE};
    use windows_sys::Win32::Storage::Xps::{
        EndDoc, EndPage, StartDocW, StartPage, DOCINFOW,
    };

    if !has_visible_ink(width, height, packed)? {
        return Err(RENDER_FAILED.into());
    }

    let printer = wide(name);
    let winspool = wide("WINSPOOL");
    let document = wide("AxizPOS receipt");

    unsafe {
        let mut handle = PRINTER_HANDLE::default();

        if OpenPrinterW(printer.as_ptr(), &mut handle, std::ptr::null()) == 0 {
            return Err(format!(
                "{} Windows error {}.",
                printer_discovery::QUEUE_CLOSED,
                GetLastError()
            ));
        }

        // Exact receipt length at 203 dpi. A longer form scales the slip, and a
        // 24-bit bitmap is large enough that this driver keeps only its first rows,
        // which are the footer. One 1-bit page holds the header through the footer.
        let mut devmode = prepare_devmode(handle, printer.as_ptr(), width, height);
        if let Some(bytes) = devmode.as_mut() {
            set_band_paper(bytes, width, height);
        }

        let devmode_ptr = devmode
            .as_ref()
            .map(|bytes| {
                bytes.as_ptr()
                    as *const windows_sys::Win32::Graphics::Gdi::DEVMODEW
            })
            .unwrap_or(std::ptr::null());

        let hdc = CreateDCW(
            winspool.as_ptr(),
            printer.as_ptr(),
            std::ptr::null(),
            devmode_ptr,
        );

        ClosePrinter(handle);

        if hdc.is_null() {
            return Err(format!(
                "{TRANSMIT_FAILED} Windows error {}.",
                GetLastError()
            ));
        }

        let result = (|| {
            let info = DOCINFOW {
                cbSize: std::mem::size_of::<DOCINFOW>() as i32,
                lpszDocName: document.as_ptr(),
                lpszOutput: std::ptr::null(),
                lpszDatatype: std::ptr::null(),
                fwType: 0,
            };

            if StartDocW(hdc, &info) <= 0 {
                return Err(format!(
                    "{TRANSMIT_FAILED} Windows error {}.",
                    GetLastError()
                ));
            }

            for _ in 0..copies.max(1) {
                if StartPage(hdc) <= 0 {
                    let _ = EndDoc(hdc);
                    return Err(format!("{TRANSMIT_FAILED} Windows error {}.", GetLastError()));
                }
                // A negative hardware offset clips the top line and the left of the totals.
                let _ = SetMapMode(hdc, MM_TEXT);
                let _ = SetViewportOrgEx(hdc, 0, 0, std::ptr::null_mut());
                let _ = SetWindowOrgEx(hdc, 0, 0, std::ptr::null_mut());
                eprintln!(
                    "ai-pos: gdi page {width}x{height} dpi={}x{} printable={}x{}",
                    GetDeviceCaps(hdc, LOGPIXELSX as i32),
                    GetDeviceCaps(hdc, LOGPIXELSY as i32),
                    GetDeviceCaps(hdc, HORZRES as i32),
                    GetDeviceCaps(hdc, VERTRES as i32),
                );
                let bits = match band_1bit(width, packed, 0, height) {
                    Ok(bits) => bits,
                    Err(message) => {
                        let _ = EndPage(hdc);
                        let _ = EndDoc(hdc);
                        return Err(message);
                    }
                };
                if let Err(message) = paint_page(hdc, width, height, &bits) {
                    let _ = EndPage(hdc);
                    let _ = EndDoc(hdc);
                    return Err(message);
                }
                if EndPage(hdc) <= 0 {
                    let _ = EndDoc(hdc);
                    return Err(format!("{TRANSMIT_FAILED} Windows error {}.", GetLastError()));
                }
            }

            if EndDoc(hdc) <= 0 {
                return Err(format!(
                    "{TRANSMIT_FAILED} Windows error {}.",
                    GetLastError()
                ));
            }

            Ok(())
        })();

        DeleteDC(hdc);
        result
    }
}

/// One copy of the whole bottom-up 1-bit bitmap. Bit 1 is black. A short copy fails.
#[cfg(windows)]
fn paint_page(
    hdc: windows_sys::Win32::Graphics::Gdi::HDC,
    width: u32,
    height: u32,
    pixels: &[u8],
) -> Result<(), String> {
    use windows_sys::Win32::Graphics::Gdi::{SetDIBitsToDevice, BITMAPINFOHEADER, DIB_RGB_COLORS, RGBQUAD};

    #[repr(C)]
    struct Info1 {
        header: BITMAPINFOHEADER,
        colors: [RGBQUAD; 2],
    }

    let stride = (width as usize).div_ceil(32) * 4;
    if height == 0 || pixels.len() != stride * height as usize {
        return Err("The receipt image is malformed.".into());
    }
    let ppm = 203 * 10_000 / 254;
    let info = Info1 {
        header: BITMAPINFOHEADER {
            biSize: std::mem::size_of::<BITMAPINFOHEADER>() as u32,
            biWidth: width as i32,
            biHeight: height as i32,
            biPlanes: 1,
            biBitCount: 1,
            biCompression: 0,
            biSizeImage: pixels.len() as u32,
            biXPelsPerMeter: ppm,
            biYPelsPerMeter: ppm,
            biClrUsed: 2,
            biClrImportant: 2,
        },
        colors: [
            RGBQUAD { rgbBlue: 255, rgbGreen: 255, rgbRed: 255, rgbReserved: 0 },
            RGBQUAD { rgbBlue: 0, rgbGreen: 0, rgbRed: 0, rgbReserved: 0 },
        ],
    };
    let copied = unsafe {
        SetDIBitsToDevice(
            hdc,
            0,
            0,
            width,
            height,
            0,
            0,
            0,
            height,
            pixels.as_ptr().cast(),
            (&info as *const Info1).cast(),
            DIB_RGB_COLORS,
        )
    };
    if copied == height as i32 {
        Ok(())
    } else {
        Err(format!(
            "The printer copied {copied} of {height} rows. The receipt was not scaled or cropped."
        ))
    }
}

#[cfg(windows)]
fn prepare_devmode(
    handle: windows_sys::Win32::Graphics::Printing::PRINTER_HANDLE,
    name: *const u16,
    width: u32,
    height: u32,
) -> Option<Vec<u8>> {
    use windows_sys::Win32::Graphics::Gdi::{
        DEVMODEW, DM_ORIENTATION, DM_PAPERLENGTH, DM_PAPERSIZE, DM_PAPERWIDTH, DM_SCALE,
        DMPAPER_USER,
    };
    use windows_sys::Win32::Graphics::Printing::DocumentPropertiesW;

    unsafe {
        let needed = DocumentPropertiesW(
            std::ptr::null_mut(), handle, name, std::ptr::null_mut(), std::ptr::null(), 0,
        );
        if needed <= 0 {
            return None;
        }

        let mut current = vec![0u8; needed as usize];
        if DocumentPropertiesW(
            std::ptr::null_mut(), handle, name, current.as_mut_ptr().cast(), std::ptr::null(), 2,
        ) < 0 {
            return None;
        }

        let apply_roll_size = |bytes: &mut [u8]| -> bool {
            if bytes.len() < std::mem::size_of::<DEVMODEW>() {
                return false;
            }
            let mode = bytes.as_mut_ptr().cast::<DEVMODEW>();
            let (paper_width, paper_length) = paper_size_tenths(width, height);
            (*mode).dmFields |=
                DM_ORIENTATION | DM_PAPERSIZE | DM_PAPERWIDTH | DM_PAPERLENGTH | DM_SCALE;
            (*mode).Anonymous1.Anonymous1.dmOrientation = 1;
            (*mode).Anonymous1.Anonymous1.dmPaperSize = DMPAPER_USER as i16;
            (*mode).Anonymous1.Anonymous1.dmPaperWidth = paper_width;
            (*mode).Anonymous1.Anonymous1.dmPaperLength = paper_length;
            (*mode).Anonymous1.Anonymous1.dmScale = 100;
            true
        };

        if !apply_roll_size(&mut current) {
            return None;
        }
        let mut updated = current.clone();
        // DM_IN_BUFFER | DM_OUT_BUFFER lets the installed driver normalize the custom form.
        if DocumentPropertiesW(
            std::ptr::null_mut(), handle, name, updated.as_mut_ptr().cast(), current.as_ptr().cast(), 10,
        ) < 0 {
            return Some(current);
        }
        if !apply_roll_size(&mut updated) {
            return None;
        }
        Some(updated)
    }
}

#[cfg(windows)]
fn wide(value: &str) -> Vec<u16> {
    value.encode_utf16().chain(std::iter::once(0)).collect()
}

#[cfg(windows)]
pub fn print_gdi_text(name: &str, text: &str, copies: u32) -> Result<(), String> {
    use windows_sys::Win32::Foundation::GetLastError;
    use windows_sys::Win32::Graphics::Gdi::{
        CreateDCW, CreateFontW, DeleteDC, DeleteObject, GetDeviceCaps, GetTextMetricsW, SelectObject, SetBkMode,
        SetTextColor, TextOutW, CLIP_DEFAULT_PRECIS, DEFAULT_CHARSET, DEFAULT_PITCH, DEFAULT_QUALITY, FW_NORMAL,
        HORZRES, LOGPIXELSY, OUT_DEFAULT_PRECIS, TEXTMETRICW, TRANSPARENT, VERTRES,
    };
    use windows_sys::Win32::Graphics::Printing::{ClosePrinter, OpenPrinterW, PRINTER_HANDLE};
    use windows_sys::Win32::Storage::Xps::{EndDoc, EndPage, StartDocW, StartPage, DOCINFOW};

    let lines: Vec<&str> = text.split('\n').map(|line| line.trim_end_matches('\r')).collect();
    if lines.iter().all(|line| line.trim().is_empty()) {
        return Err(printer_discovery::RENDER_FAILED.into());
    }
    let printer = wide(name);
    let winspool = wide("WINSPOOL");
    let document = wide("AxizPOS receipt");
    let face = wide("Courier New");
    unsafe {
        let mut handle = PRINTER_HANDLE::default();
        if OpenPrinterW(printer.as_ptr(), &mut handle, std::ptr::null()) == 0 {
            return Err(format!("{} Windows error {}.", printer_discovery::QUEUE_CLOSED, GetLastError()));
        }
        let height_dots = (lines.len() as u32).saturating_mul(28).max(400);
        let devmode = prepare_devmode(handle, printer.as_ptr(), 576, height_dots);
        let devmode_ptr = devmode
            .as_ref()
            .map(|bytes| bytes.as_ptr() as *const windows_sys::Win32::Graphics::Gdi::DEVMODEW)
            .unwrap_or(std::ptr::null());
        let mut hdc = CreateDCW(winspool.as_ptr(), printer.as_ptr(), std::ptr::null(), devmode_ptr);
        if hdc.is_null() {
            hdc = CreateDCW(winspool.as_ptr(), printer.as_ptr(), std::ptr::null(), std::ptr::null());
        }
        ClosePrinter(handle);
        if hdc.is_null() {
            return Err(format!("{TRANSMIT_FAILED} Windows error {}.", GetLastError()));
        }
        let drawn = (|| {
            let info = DOCINFOW {
                cbSize: std::mem::size_of::<DOCINFOW>() as i32,
                lpszDocName: document.as_ptr(),
                lpszOutput: std::ptr::null(),
                lpszDatatype: std::ptr::null(),
                fwType: 0,
            };
            if StartDocW(hdc, &info) <= 0 {
                return Err(format!("{TRANSMIT_FAILED} Windows error {}.", GetLastError()));
            }
            let dpi = GetDeviceCaps(hdc, LOGPIXELSY as i32).max(96);
            let font = CreateFontW(
                -(dpi * 10 / 72).max(12),
                0,
                0,
                0,
                FW_NORMAL as i32,
                0,
                0,
                0,
                DEFAULT_CHARSET as u32,
                OUT_DEFAULT_PRECIS as u32,
                CLIP_DEFAULT_PRECIS as u32,
                DEFAULT_QUALITY as u32,
                DEFAULT_PITCH as u32,
                face.as_ptr(),
            );
            if font.is_null() {
                let _ = EndDoc(hdc);
                return Err(format!("{TRANSMIT_FAILED} Windows error {}.", GetLastError()));
            }
            let previous = SelectObject(hdc, font);
            SetBkMode(hdc, TRANSPARENT as i32);
            SetTextColor(hdc, 0);
            let mut metrics = TEXTMETRICW::default();
            if GetTextMetricsW(hdc, &mut metrics) == 0 {
                SelectObject(hdc, previous);
                let _ = DeleteObject(font);
                let _ = EndDoc(hdc);
                return Err(format!("{TRANSMIT_FAILED} Windows error {}.", GetLastError()));
            }
            let line_h = (metrics.tmHeight + metrics.tmExternalLeading).max(12);
            let page_h = GetDeviceCaps(hdc, VERTRES as i32).max(line_h + 40);
            let margin = (GetDeviceCaps(hdc, HORZRES as i32) / 20).clamp(8, 48);
            for _ in 0..copies.max(1) {
                if StartPage(hdc) <= 0 {
                    SelectObject(hdc, previous);
                    let _ = DeleteObject(font);
                    let _ = EndDoc(hdc);
                    return Err(format!("{TRANSMIT_FAILED} Windows error {}.", GetLastError()));
                }
                let mut y = margin;
                for line in &lines {
                    if y + line_h > page_h - margin {
                        if EndPage(hdc) <= 0 || StartPage(hdc) <= 0 {
                            SelectObject(hdc, previous);
                            let _ = DeleteObject(font);
                            let _ = EndDoc(hdc);
                            return Err(format!("{TRANSMIT_FAILED} Windows error {}.", GetLastError()));
                        }
                        y = margin;
                    }
                    let wide_line = wide(line);
                    let count = wide_line.len().saturating_sub(1) as i32;
                    if count > 0 && TextOutW(hdc, margin, y, wide_line.as_ptr(), count) == 0 {
                        let _ = EndPage(hdc);
                        SelectObject(hdc, previous);
                        let _ = DeleteObject(font);
                        let _ = EndDoc(hdc);
                        return Err(format!("{TRANSMIT_FAILED} Windows error {}.", GetLastError()));
                    }
                    y += line_h;
                }
                if EndPage(hdc) <= 0 {
                    SelectObject(hdc, previous);
                    let _ = DeleteObject(font);
                    let _ = EndDoc(hdc);
                    return Err(format!("{TRANSMIT_FAILED} Windows error {}.", GetLastError()));
                }
            }
            SelectObject(hdc, previous);
            let _ = DeleteObject(font);
            if EndDoc(hdc) <= 0 {
                return Err(format!("{TRANSMIT_FAILED} Windows error {}.", GetLastError()));
            }
            Ok(())
        })();
        DeleteDC(hdc);
        drawn
    }
}

